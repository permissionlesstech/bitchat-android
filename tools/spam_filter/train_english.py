#!/usr/bin/env python3
"""Generate the fixed English character model from the adjacent synthetic corpus.

Uses only Python's standard library. Does not read messages or contact services.
Run from any directory; --check verifies the checked-in model without writing it.
"""

import argparse
import hashlib
import math
from pathlib import Path


ALPHABET = "abcdefghijklmnopqrstuvwxyz "
SMOOTHING = 0.1


def generate(corpus: bytes) -> str:
    positions = {char: index for index, char in enumerate(ALPHABET)}
    counts = [[SMOOTHING] * len(ALPHABET) for _ in ALPHABET]
    for line in corpus.decode("utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        if any(char not in ALPHABET for char in line):
            raise ValueError("Training examples must contain lowercase English letters and spaces")
        normalized = " ".join(line.split())
        for first, second in zip(normalized, normalized[1:]):
            counts[positions[first]][positions[second]] += 1
    rows = []
    for row in counts:
        total = sum(row)
        rows.append("        " + ", ".join(f"{-math.log(value / total):.6f}f" for value in row) + ",")
    digest = hashlib.sha256(corpus).hexdigest()
    return f'''package com.bitchat.android.spam

// Generated by tools/spam_filter/train_english.py; edit the synthetic corpus, not this table.
// Alphabet: lowercase a-z followed by space. Additive smoothing: {SMOOTHING}.
// Corpus SHA-256: {digest}
internal object EnglishMarkovModel {{
    const val ALPHABET_SIZE = 27

    // Negative natural log probabilities P(next | previous), row-major, 729 float32 weights.
    private val costs = floatArrayOf(
{chr(10).join(rows)}
    )

    fun cost(previous: Int, next: Int): Float = costs[previous * ALPHABET_SIZE + next]
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    directory = Path(__file__).resolve().parent
    target = directory.parents[1] / "app/src/main/java/com/bitchat/android/spam/EnglishMarkovModel.kt"
    generated = generate((directory / "english-training.txt").read_bytes())
    if arguments.check:
        if not target.exists() or target.read_text() != generated:
            raise SystemExit("English model differs; regenerate with tools/spam_filter/train_english.py")
        print("English model matches its synthetic training corpus (729 weights; 2916 weight bytes).")
    else:
        target.write_text(generated)
        print("Generated EnglishMarkovModel.kt (729 weights; 2916 weight bytes).")


if __name__ == "__main__":
    main()
